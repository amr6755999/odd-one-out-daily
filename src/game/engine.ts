export type DifferenceMode = 'color' | 'rotation' | 'size' | 'symbol';
export type ShapeKind = 'triangle' | 'diamond' | 'pentagon' | 'hexagon' | 'burst' | 'ticket';
export type SymbolKind = 'star' | 'dot' | 'cross' | 'ring' | 'heart';

export interface PuzzleTile {
  id: number;
  color: string;
  rotation: number;
  scale: number;
  symbol: SymbolKind;
}

export interface PuzzleRound {
  index: number;
  rows: number;
  columns: number;
  mode: DifferenceMode;
  shape: ShapeKind;
  tiles: PuzzleTile[];
  oddIndex: number;
  seconds: number;
}

export interface DailyChallenge {
  date: string;
  seed: number;
  rounds: PuzzleRound[];
}

export interface RunScore {
  correct: number;
  mistakes: number;
  elapsedSeconds: number;
  score: number;
}

export interface GameHistoryEntry extends RunScore {
  date: string;
  mode: 'daily' | 'practice';
  finishedAt: number;
}

const MODES: DifferenceMode[] = ['color', 'rotation', 'size', 'symbol'];
const SHAPES: ShapeKind[] = ['triangle', 'diamond', 'pentagon', 'hexagon', 'burst', 'ticket'];
const SYMBOLS: SymbolKind[] = ['star', 'dot', 'cross', 'ring', 'heart'];
const COLORS = ['#6C63FF', '#FF6584', '#22A699', '#F4A62A', '#3386E8', '#D94FAD'];
const ODD_COLORS = ['#F45151', '#197A67', '#7D43C7', '#D47B00', '#1685A0', '#B52B72'];

/** Small xorshift PRNG. Avoid Math.random so puzzles can be reproduced anywhere. */
export function createRandom(seed: number): () => number {
  let state = seed >>> 0 || 0x6d2b79f5;
  return () => {
    state ^= state << 13;
    state ^= state >>> 17;
    state ^= state << 5;
    return (state >>> 0) / 4294967296;
  };
}

/** FNV-1a hash; stable across browser engines and machines. */
export function hashSeed(value: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < value.length; i += 1) {
    hash ^= value.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

export function getUtcDate(date = new Date()): string {
  return date.toISOString().slice(0, 10);
}

export function isValidDateKey(value: string | null | undefined): value is string {
  if (!value || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const parsed = new Date(`${value}T00:00:00.000Z`);
  return !Number.isNaN(parsed.getTime()) && getUtcDate(parsed) === value;
}

function pick<T>(items: readonly T[], random: () => number): T {
  return items[Math.floor(random() * items.length)]!;
}

function shuffle<T>(items: T[], random: () => number): T[] {
  for (let i = items.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [items[i], items[j]] = [items[j]!, items[i]!];
  }
  return items;
}

export function createDailyChallenge(date: string): DailyChallenge {
  if (!isValidDateKey(date)) throw new Error(`Invalid challenge date: ${date}`);
  const seed = hashSeed(`odd-one-out-daily:${date}:v1`);
  const random = createRandom(seed);
  const rounds: PuzzleRound[] = [];
  const sizes = [4, 4, 5, 5, 6];
  const modeOrder = shuffle([...MODES], random);

  for (let index = 0; index < 5; index += 1) {
    const mode = modeOrder[index % modeOrder.length]!;
    const rows = sizes[index]!;
    const columns = sizes[index]!;
    const count = rows * columns;
    const shape = mode === 'rotation'
      ? pick(['triangle', 'diamond', 'pentagon', 'ticket'] as const, random)
      : pick(SHAPES, random);
    const commonColor = pick(COLORS, random);
    let oddColor = pick(ODD_COLORS.filter((color) => color !== commonColor), random);
    while (oddColor === commonColor) oddColor = pick(ODD_COLORS, random);
    const commonSymbol = pick(SYMBOLS, random);
    const oddSymbol = pick(SYMBOLS.filter((symbol) => symbol !== commonSymbol), random);
    const oddIndex = Math.floor(random() * count);

    const tiles = Array.from({ length: count }, (_, id): PuzzleTile => ({
      id,
      color: mode === 'color' && id === oddIndex ? oddColor : commonColor,
      rotation: mode === 'rotation' && id === oddIndex ? 42 : 0,
      scale: mode === 'size' && id === oddIndex ? 0.64 : 1,
      symbol: mode === 'symbol' && id === oddIndex ? oddSymbol : commonSymbol,
    }));

    // A single property changes for exactly one tile. The odd tile is never
    // generated by random mutation; its index is selected exactly once.
    rounds.push({ index, rows, columns, mode, shape, tiles, oddIndex, seconds: 12 });
  }

  return { date, seed, rounds };
}

export function createPracticeChallenge(seed = Date.now()): DailyChallenge {
  // Practice challenges use the same tested generator, but with a unique stable
  // date-shaped seed namespace, keeping practice separate from daily puzzles.
  const boundedSeed = Math.abs(Math.floor(Number.isFinite(seed) ? seed : Date.now()));
  // Keep the synthetic date within four-digit ISO years; it is just a base
  // layout seed for practice, never the user's daily date or streak date.
  const date = new Date(Date.UTC(2000, 0, 1) + (boundedSeed % 30_000_000_000_000)).toISOString().slice(0, 10);
  const challenge = createDailyChallenge(date);
  const random = createRandom((seed >>> 0) ^ 0xa5a5a5a5);
  const rounds = challenge.rounds.map((round) => {
    const mode = pick(MODES, random);
    const shape = mode === 'rotation'
      ? pick(['triangle', 'diamond', 'pentagon', 'ticket'] as const, random)
      : pick(SHAPES, random);
    const commonColor = pick(COLORS, random);
    const oddColor = pick(ODD_COLORS.filter((color) => color !== commonColor), random);
    const commonSymbol = pick(SYMBOLS, random);
    const oddSymbol = pick(SYMBOLS.filter((symbol) => symbol !== commonSymbol), random);
    const oddIndex = Math.floor(random() * round.tiles.length);
    const tiles = round.tiles.map((tile, i) => ({
      ...tile,
      color: mode === 'color' && i === oddIndex ? oddColor : commonColor,
      rotation: mode === 'rotation' && i === oddIndex ? 42 : 0,
      scale: mode === 'size' && i === oddIndex ? 0.64 : 1,
      symbol: mode === 'symbol' && i === oddIndex ? oddSymbol : commonSymbol,
    }));
    return { ...round, mode, shape, tiles, oddIndex, seconds: 12 };
  });
  return { date: `practice-${seed}`, seed: seed >>> 0, rounds };
}

export function calculateScore(correct: number, mistakes: number): number {
  if (!Number.isFinite(correct) || !Number.isFinite(mistakes)) return 0;
  const safeCorrect = Math.max(0, Math.floor(correct));
  const safeMistakes = Math.max(0, Math.floor(mistakes));
  return Math.max(0, safeCorrect * 100 - safeMistakes * 20);
}

export function createRunScore(correct: number, mistakes: number, elapsedMilliseconds: number): RunScore {
  const elapsedSeconds = Math.max(0, Math.round(Math.max(0, elapsedMilliseconds) / 100) / 10);
  return {
    correct: Math.max(0, Math.floor(correct)),
    mistakes: Math.max(0, Math.floor(mistakes)),
    elapsedSeconds,
    score: calculateScore(correct, mistakes),
  };
}

export function compareScores(a: Pick<RunScore, 'score' | 'elapsedSeconds'>, b: Pick<RunScore, 'score' | 'elapsedSeconds'>): number {
  if (a.score !== b.score) return a.score - b.score;
  return b.elapsedSeconds - a.elapsedSeconds; // A smaller time wins a tie.
}
